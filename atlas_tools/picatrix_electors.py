#!/usr/bin/env python3
"""The electors test: did the people who COULD have timed by the stars actually do it?

picatrix_election.py found the atlas as a whole shows no Mercury timing (17% of creations with
Mercury in its own signs, against 17% by chance). nodus1's point: a null over everyone can hide a
signal in the few who had an almanac, a reason and the Picatrix tradition in hand. So take only
them, and test them against chance AT THEIR OWN SMALL SIZE: an exact binomial tail, because at
n of 10 one hit is noise and three looks like a revelation.

The electors, chosen before looking at their results: the Picatrix's own line and the
astrological magicians and astronomers who read it or its tradition, plus the Medici, who
commissioned Ficino. Ficino and Alfonso X joined on 2026-10-13, when their journeys were built
for this test; their acts are picked by hand (see CURATED).

    python3 atlas_tools/picatrix_electors.py      # writes readings/picatrix_electors.md
"""
import sys
from math import comb
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import picatrix_election as P  # noqa: E402

ELECTORS = [
    "maslama_al_qurtubi", "maslama_al_majriti", "al_kindi", "albertus_magnus", "roger_bacon",
    "ramon_llull", "cosimo_de_medici", "lorenzo_de_medici_il_magnifico",
    "giovanni_pico_della_mirandola", "johannes_trithemius", "heinrich_cornelius_agrippa",
    "paracelsus", "john_dee", "giordano_bruno", "tommaso_campanella", "johannes_kepler",
    "robert_fludd",
]
# Ficino and Alfonso X, added 2026-10-13 when their journeys landed. Their stop names rarely
# carry the classifier's keywords ("the long letter to Francesco Capponi", "the banquet on
# Plato's day"), and one false hit ("the hour written down" is his birth), so for these two the
# acts are picked by hand from their journeys: things the person made, issued or chose to hold.
# Ordinations, appointments, deaths and sieges are left out: their days were not his to choose.
CURATED = {
    "marsilio_ficino": {
        "1458-01-24": "book", "1468-11-07": "performance", "1482-11-07": "book",
        "1489-09-15": "book", "1494-12-12": "book", "1495-03-11": "book",
        "1498-05-24": "book", "1499-09-27": "book",
    },
    "alfonso_x_el_sabio": {
        "1244-03-26": "founding", "1249-01-29": "founding", "1282-11-09": "book",
    },
}
ELECTORS += list(CURATED)
P_DIGNIFIED = 1 / 6      # Mercury in Gemini or Virgo, roughly, over the long run
P_WEDNESDAY = 1 / 7


def tail(k, n, p):
    """P(X >= k) for X ~ Binomial(n, p)."""
    return sum(comb(n, i) * p ** i * (1 - p) ** (n - i) for i in range(k, n + 1))


def main():
    cs = [c for c in P.collect() if c["slug"] in ELECTORS and c["slug"] not in CURATED]
    for r in P.journey_rows_not_in_catalog(set()):
        kind = CURATED.get(r["slug"], {}).get(r["date"])
        if kind:
            cs.append(dict(r, kind=kind + " (picked by hand)", sky=P.read_sky(r["date"])))
    n = len(cs)
    dig = [c for c in cs if c["sky"]["mercury"].split()[0] in P.DOMICILE]
    wed = [c for c in cs if c["sky"]["weekday"].startswith("Wednesday")]
    pos = [c for c in cs if c["sky"]["score"] > 0]
    by = {}
    for c in cs:
        by.setdefault(c["slug"], []).append(c)
    o = ["# The electors test: Mercury timing among those who could have elected\n",
         "Generated by `atlas_tools/picatrix_electors.py` on top of `picatrix_election.py`, same "
         "method and limits (keyword-found creations, day-precise dates only, sky at 12:00 UT).\n",
         "**Electors tested (%d subjects, chosen before looking):** %s. Ficino's and Alfonso X's "
         "acts are picked by hand from their journeys (things they made, issued or chose to "
         "hold; not ordinations, appointments or deaths), marked 'picked by hand' below.\n"
         % (len(ELECTORS), ", ".join(ELECTORS)),
         "**Day-precise creations among them:** %d, from %d of the %d subjects (%s).\n"
         % (n, len(by), len(ELECTORS), ", ".join("%s %d" % (s, len(v)) for s, v in sorted(by.items()))),
         "\n## Result\n",
         "- Mercury in its own signs: **%d of %d** (expected %.1f). Chance of %d or more: **%.2f**.\n"
         % (len(dig), n, n * P_DIGNIFIED, len(dig), tail(len(dig), n, P_DIGNIFIED) if n else 1),
         "- Made on a Wednesday: **%d of %d** (expected %.1f). Chance of %d or more: **%.2f**.\n"
         % (len(wed), n, n * P_WEDNESDAY, len(wed), tail(len(wed), n, P_WEDNESDAY) if n else 1),
         "- Mercury score above zero: %d of %d.\n" % (len(pos), n),
         "\nA chance of 0.05 or less would be worth a second look. Anything above it is what "
         "random dates give.\n",
         "\n**What this test could see (nodus1's point).** At n = %d, the smallest Mercury count "
         "that would reach 0.05 is %s, i.e. electing on Mercury for %s of everything they made. "
         "Anything short of that was invisible. So the honest reading is that the question is "
         "NOT TESTABLE at this size, not that the answer is no, unless the count reaches that "
         "threshold.\n"
         % ((n,) + ((lambda k: (("%d of %d" % (k, n)), ("%.0f%%" % (100.0 * k / n))))(
             next((k for k in range(n + 1) if tail(k, n, P_DIGNIFIED) <= 0.05), None))
            if n and any(tail(k, n, P_DIGNIFIED) <= 0.05 for k in range(n + 1))
            else ("no count at all", "any share"))),
         "\n## Every elector creation, oldest first\n"]
    o += [P.line(c) for c in sorted(cs, key=lambda c: c["date"])]
    out = P.ATLAS / "readings" / "picatrix_electors.md"
    out.write_text("".join(o), encoding="utf-8")
    print("%d elector creations; dignified %d, Wednesday %d; report at %s" % (n, len(dig), len(wed), out))
    print("P(dig>=k)=%.3f  P(wed>=k)=%.3f" % (tail(len(dig), n, P_DIGNIFIED), tail(len(wed), n, P_WEDNESDAY)))


if __name__ == "__main__":
    main()
