#!/usr/bin/env python3
"""The electors test: did the people who COULD have timed by the stars actually do it?

picatrix_election.py found the atlas as a whole shows no Mercury timing (17% of creations with
Mercury in its own signs, against 17% by chance). nodus1's point: a null over everyone can hide a
signal in the few who had an almanac, a reason and the Picatrix tradition in hand. So take only
them, and test them against chance AT THEIR OWN SMALL SIZE: an exact binomial tail, because at
n of 10 one hit is noise and three looks like a revelation.

The electors, chosen before looking at their results: the Picatrix's own line and the
astrological magicians and astronomers who read it or its tradition, plus the Medici, who
commissioned Ficino. Ficino and Alfonso X joined on 2026-10-13, when their journeys were built
for this test; their acts are picked by hand (see CURATED).

    python3 atlas_tools/picatrix_electors.py      # writes readings/picatrix_electors.md
"""
import sys
from math import comb
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import picatrix_election as P  # noqa: E402

ELECTORS = [
    "maslama_al_qurtubi", "maslama_al_majriti", "al_kindi", "albertus_magnus", "roger_bacon",
    "ramon_llull", "cosimo_de_medici", "lorenzo_de_medici_il_magnifico",
    "giovanni_pico_della_mirandola", "johannes_trithemius", "heinrich_cornelius_agrippa",
    "paracelsus", "john_dee", "giordano_bruno", "tommaso_campanella", "johannes_kepler",
    "robert_fludd",
]
# Ficino and Alfonso X, added 2026-10-13 when their journeys landed. Their acts are selected by
# the same classifier as everyone else's, with no hand-picking: an earlier version picked them
# by hand after some of their skies had been seen, which nodus1 rightly called unauditable.
ELECTORS += ["marsilio_ficino", "alfonso_x_el_sabio"]
P_DIGNIFIED = 1 / 6      # Mercury in Gemini or Virgo, roughly, over the long run
P_WEDNESDAY = 1 / 7


def tail(k, n, p):
    """P(X >= k) for X ~ Binomial(n, p)."""
    return sum(comb(n, i) * p ** i * (1 - p) ** (n - i) for i in range(k, n + 1))


def threshold(n):
    k = next((k for k in range(n + 1) if tail(k, n, P_DIGNIFIED) <= 0.05), None) if n else None
    return ("%d of %d (%.0f%%)" % (k, n, 100.0 * k / n)) if k is not None else "no count at all"


def result_block(cs, title):
    n = len(cs)
    dig = sum(1 for c in cs if c["sky"]["mercury"].split()[0] in P.DOMICILE)
    wed = sum(1 for c in cs if c["sky"]["weekday"].startswith("Wednesday"))
    pos = sum(1 for c in cs if c["sky"]["score"] > 0)
    by = {}
    for c in cs:
        by[c["slug"]] = by.get(c["slug"], 0) + 1
    text = ("\n## %s\n" % title +
            "Creations: %d, from %d subjects (%s).\n\n" % (n, len(by), ", ".join("%s %d" % kv for kv in sorted(by.items()))) +
            "- Mercury in its own signs: **%d of %d** (expected %.1f). Chance of %d or more: **%.2f**.\n"
            % (dig, n, n * P_DIGNIFIED, dig, tail(dig, n, P_DIGNIFIED) if n else 1) +
            "- Made on a Wednesday: **%d of %d** (expected %.1f). Chance of %d or more: **%.2f**.\n"
            % (wed, n, n * P_WEDNESDAY, wed, tail(wed, n, P_WEDNESDAY) if n else 1) +
            "- Mercury score above zero: %d of %d.\n" % (pos, n) +
            "- Smallest Mercury count this n could detect at 0.05: %s.\n" % threshold(n))
    return text, (n, dig, wed)


def main():
    primary = [c for c in P.collect(wide=False) if c["slug"] in ELECTORS]
    secondary = [c for c in P.collect(wide=True) if c["slug"] in ELECTORS]
    o = ["# The electors test: Mercury timing among those who could have elected\n",
         "Generated by `atlas_tools/picatrix_electors.py` on top of `picatrix_election.py` "
         "(day-precise dates only, sky at 12:00 UT).\n",
         "\n## Hypothesis and rule, stated before the numbers\n",
         "**Hypothesis.** If the people below elected their acts by Mercury, as Ficino's *De vita* "
         "teaches for works of the mind, their creations will show Mercury in its own signs, or "
         "fall on Wednesdays, more often than chance (about 1 in 6 and 1 in 7). This is a test of "
         "Mercury, Ficino's emphasis. The Picatrix's own timing tool, the Moon's mansion, is a "
         "SEPARATE test and is not reported here.\n",
         "**Electors (%d subjects, chosen before looking):** %s.\n"
         % (len(ELECTORS), ", ".join(ELECTORS)),
         "**Selection rule, mechanical.** A creation is any day-precise stop, not a journey's first "
         "stop (the birth), whose NAME matches the classifier in `picatrix_election.py`, minus its "
         "exclusions. No stop is added or removed by hand.\n",
         "**Two classifiers, in a fixed order.** PRIMARY: the classifier as reviewed on "
         "2026-10-12, before any elector result was seen (`KINDS_V1`). SECONDARY: the wider one, "
         "adding letters, apologias, wills, decrees, sentences, banquets and treaties. It was "
         "chosen on 2026-10-13 AFTER the electors had come back null, so it is a choice made with "
         "the result in view and is labelled as such. The doctrinal case for some of it (election "
         "manuals do elect for letters and petitions to kings) is not yet cited to the Picatrix's "
         "text, so it stays secondary until it is. Marriages are excluded from both: they are "
         "Venus's matter, not Mercury's.\n"]
    t1, (n1, d1, w1) = result_block(primary, "PRIMARY result: the classifier fixed before looking")
    t2, (n2, d2, w2) = result_block(secondary, "SECONDARY result: the wider classifier, chosen after the null")
    o += [t1, t2,
          "\nA chance of 0.05 or less would be worth a second look. Anything above it is what "
          "random dates give. Below the detection threshold, the honest reading is NOT TESTABLE "
          "at this size, not 'no'.\n",
          "\n## Every elector creation (secondary set, which contains the primary), oldest first\n"]
    o += [P.line(c) for c in sorted(secondary, key=lambda c: c["date"])]
    out = P.ATLAS / "readings" / "picatrix_electors.md"
    out.write_text("".join(o), encoding="utf-8")
    print("primary n=%d dig=%d wed=%d | secondary n=%d dig=%d wed=%d | %s" % (n1, d1, w1, n2, d2, w2, out))


if __name__ == "__main__":
    main()
